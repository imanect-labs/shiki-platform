def assign_split(rows, dev_count, rng):
    """紛らわしい・注入の行は書いた split のまま、残りの普通の行から dev を種つきで選ぶ。"""
    fixed_dev = sum(1 for r in rows if r["split"] == "dev")
    plain = [i for i, r in enumerate(rows) if r["split"] is None]
    need = dev_count - fixed_dev
    assert 0 <= need <= len(plain), (dev_count, fixed_dev, len(plain))
    dev = set(rng.sample(plain, need))
    for i in plain:
        rows[i]["split"] = "dev" if i in dev else "test"


def build_inquiries(rng):
    out = []
    for cat, rows in INQUIRY.items():
        assert len(rows) == INQUIRY_TOTAL[cat], (cat, len(rows))
        rows = [dict(r) for r in rows]
        assign_split(rows, INQUIRY_DEV[cat], rng)
        for r in rows:
            out.append({
                "split": r["split"],
                "state": {
                    "件名": r["subject"],
                    "本文": r["body"],
                    "差出人": r["sender"] or rng.choice(SENDERS),
                },
                "labels": {"category": cat, "priority": r["priority"], "angry": r["angry"]},
                "tags": {
                    "ambiguous": r["ambiguous"],
                    "injection": r["inject"] is not None,
                    "inject_target": r["inject"],
                    "note": r["note"],
                },
            })
    return out


