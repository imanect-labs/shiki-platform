EXPENSE_DEV = {"normal": 20, "hard": 4, "rule": 4, "judge": 10, "inject": 2}
EXPENSE_TOTAL = {"normal": 60, "hard": 12, "rule": 12, "judge": 30, "inject": 6}


def pick_date(spec, rng):
    days = [DATE_FROM + dt.timedelta(days=i) for i in range((DATE_TO - DATE_FROM).days + 1)]
    want = {
        None: (0, 1, 2, 3, 4), "sat": (5,), "sun": (6,), "fri": (4,),
    }[spec]
    return rng.choice([d for d in days if d.weekday() in want])


def build_expenses(rng):
    out = []
    groups = {"normal": NORMAL, "hard": HARD, "rule": RULE, "judge": JUDGE, "inject": INJECT}
    for kind, rows in groups.items():
        assert len(rows) == EXPENSE_TOTAL[kind], (kind, len(rows))
        rows = [dict(r) for r in rows]
        assign_split(rows, EXPENSE_DEV[kind], rng)
        for e in rows:
            date = pick_date(e["date"], rng)
            flags = rule_flags(e, date)
            # 作り方の検査: 規程のフラグが出るのは「規程で分かるもの」だけ（ほかは中身で判断させる）。
            assert bool(flags) == (kind == "rule"), (kind, e["purpose"], flags)
            state = {
                "申請者": rng.choice(APPLICANTS),
                "部署": e["department"] or rng.choice(DEPARTMENTS),
                "利用日": f"{date.isoformat()}（{WEEKDAYS[date.weekday()]}）",
                "費目": e["category"],
                "金額": e["amount"],
            }
            if e["people"] is not None:
                state["人数"] = e["people"]
            if e["attendees"] is not None:
                state["参加者"] = e["attendees"]
            state.update({
                "支払先": e["vendor"],
                "品名・内容": e["item"],
                "摘要": e["purpose"],
                "領収書": e["receipt"],
            })
            out.append({
                "split": e["split"],
                "state": state,
                "rule_flags": flags,
                "labels": {
                    "needs_review": kind in ("rule", "judge", "inject"),
                    "purpose_mismatch": e["mismatch"],
                    "private_use_suspected": e["private"],
                },
                "tags": {"kind": kind, "injection": kind == "inject", "note": e["note"]},
            })
    return out


def write(name, prefix, rows, rng):
    rng.shuffle(rows)
    path = OUT / f"{name}.jsonl"
    with path.open("w", encoding="utf-8") as f:
        for i, r in enumerate(rows, 1):
            f.write(json.dumps({"id": f"{prefix}-{i:03d}", **r}, ensure_ascii=False) + "\n")
    dev = sum(1 for r in rows if r["split"] == "dev")
    print(f"{path.relative_to(ROOT.parent.parent)}: {len(rows)} 件（dev {dev}・test {len(rows) - dev}）")


def main():
    rng = random.Random(SEED)
    inquiries = build_inquiries(rng)
    expenses = build_expenses(rng)
    assert len(inquiries) == 120 and len(expenses) == 120
    assert sum(1 for r in inquiries if r["split"] == "dev") == 40
    assert sum(1 for r in inquiries if r["tags"]["ambiguous"]) == 15
    assert sum(1 for r in inquiries if r["tags"]["injection"]) == 6
    assert sum(1 for r in expenses if r["split"] == "dev") == 40
    assert sum(1 for r in expenses if r["labels"]["needs_review"]) == 48
    OUT.mkdir(exist_ok=True)
    write("inquiry_triage", "inq", inquiries, rng)
    write("expense_policy", "exp", expenses, rng)


if __name__ == "__main__":
    main()
