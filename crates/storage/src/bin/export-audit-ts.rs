//! 監査ログの操作の種類（[`storage::audit::AuditAction`]）と分類を TypeScript へ出力する（#830）。
//!
//! 使い方: `cargo run -p shiki-storage --bin export-audit-ts -- <出力先ディレクトリ>`
//! 既定の出力先は `web/src/generated`。生成物は commit せず、`pnpm gen:api` から再生成する。

// CLI バイナリ: 標準エラーへの出力は正当な用途のため print 系 lint を許容する。
#![allow(clippy::print_stderr)]

use std::{fmt::Write as _, fs, path::PathBuf};

use storage::audit::{AuditAction, AuditCategory};

/// TS の文字列リテラル（JSON の文字列表記は TS でもそのまま使える）。
fn lit(s: &str) -> String {
    serde_json::Value::from(s).to_string()
}

fn render() -> String {
    let mut out = String::new();
    out.push_str(
        "// @generated by `cargo run -p shiki-storage --bin export-audit-ts`. 編集しないこと。\n",
    );
    out.push_str("// 監査ログの操作の語彙の単一ソース: crates/storage/src/audit_action.rs\n\n");
    let union = |items: Vec<String>| items.join(" | ");
    // String への write! は無謬（fmt::Result は常に Ok）なので結果は破棄する。
    let _ = writeln!(
        out,
        "export type AuditCategory = {};\n",
        union(AuditCategory::ALL.iter().map(|c| lit(c.as_str())).collect())
    );
    let _ = writeln!(
        out,
        "export type AuditAction = {};\n",
        union(AuditAction::ALL.iter().map(|a| lit(a.as_str())).collect())
    );
    out.push_str(
        "/** 分類（表示順）。 */\nexport const AUDIT_CATEGORIES: readonly { id: AuditCategory; label: string }[] = [\n",
    );
    for c in AuditCategory::ALL {
        let _ = writeln!(
            out,
            "  {{ id: {}, label: {} }},",
            lit(c.as_str()),
            lit(c.label())
        );
    }
    out.push_str("];\n\n");
    out.push_str(
        "/** 操作の種類（表示名と分類）。 */\nexport const AUDIT_ACTIONS: readonly { action: AuditAction; label: string; category: AuditCategory }[] = [\n",
    );
    for a in AuditAction::ALL {
        let _ = writeln!(
            out,
            "  {{ action: {}, label: {}, category: {} }},",
            lit(a.as_str()),
            lit(a.label()),
            lit(a.category().as_str())
        );
    }
    out.push_str("];\n");
    out
}

fn main() -> std::io::Result<()> {
    let out_dir = PathBuf::from(
        std::env::args()
            .nth(1)
            .unwrap_or_else(|| "web/src/generated".to_string()),
    );
    fs::create_dir_all(&out_dir)?;
    let out_file = out_dir.join("audit-actions.ts");
    fs::write(&out_file, render())?;
    eprintln!("wrote {}", out_file.display());
    Ok(())
}
