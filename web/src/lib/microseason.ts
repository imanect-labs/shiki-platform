const PHASES = ["初候", "次候", "末候"] as const;

const RAD = Math.PI / 180;

/// ΔT = TT − UTC（2020 年代の値。年 0.1 秒程度しか動かないので定数で持つ）。
const DELTA_T_MS = 69_000;

/// 太陽の視黄経（度・0〜360）。Meeus『Astronomical Algorithms』25 章の低精度式。
/// 誤差は 0.01° 程度（境目の時刻で十数分）で、日単位の判定には十分。
/// 式は力学時（TT）で書かれているので、UTC との差 ΔT（2020 年代で約 69 秒）を足してから使う。
export function solarLongitude(at: Date): number {
  const jd = (at.getTime() + DELTA_T_MS) / 86_400_000 + 2_440_587.5;
  const t = (jd - 2_451_545) / 36_525;
  const l0 = 280.46646 + 36_000.76983 * t + 0.0003032 * t * t;
  const m = (357.52911 + 35_999.05029 * t - 0.0001537 * t * t) * RAD;
  const c =
    (1.914602 - 0.004817 * t - 0.000014 * t * t) * Math.sin(m) +
    (0.019993 - 0.000101 * t) * Math.sin(2 * m) +
    0.000289 * Math.sin(3 * m);
  const omega = (125.04 - 1934.136 * t) * RAD;
  const apparent = l0 + c - 0.00569 - 0.00478 * Math.sin(omega);
  return ((apparent % 360) + 360) % 360;
}

/// 日本時間 0 時の UTC との差（ミリ秒）。
const JST_OFFSET_MS = 9 * 3_600_000;

/// 与えた日（端末の暦日。表示する日付と揃える）の候を返す。
/// その日の日本時間 24 時の時点で黄経がどの 5° 区間にあるかで決める
/// （＝その日のうちに境目を越えたら、その日が新しい候の初日）。
export function microSeasonOf(date: Date): MicroSeason {
  const endOfDayJst =
    Date.UTC(date.getFullYear(), date.getMonth(), date.getDate() + 1) - JST_OFFSET_MS - 1;
  const lambda = solarLongitude(new Date(endOfDayJst));
  const index = Math.floor((((lambda - 315) % 360) + 360) % 360 / 5) % 72;
  const [name, reading, meaning] = ROWS[index]!;
  return {
    name,
    reading,
    meaning,
    term: TERMS[Math.floor(index / 3)]!,
    phase: PHASES[index % 3]!,
  };
}
