/// 月日を 1 本の数直線に載せる（3 月 1 日 = 301）。年をまたぐ比較を単純にするため。
const key = (month: number, day: number) => month * 100 + day;

/// 与えた日（端末のローカル日付）の候を返す。
export function microSeasonOf(date: Date): MicroSeason {
  const today = key(date.getMonth() + 1, date.getDate());
  // 始まる日が今日以前のうち最も遅い候。1 月 1〜4 日は前年の「雪下出麦」（12/31 始まり）に当たる。
  let hit: Row = ROWS.find(([m, d]) => m === 12 && d === 31)!;
  let best = -1;
  for (const row of ROWS) {
    const start = key(row[0], row[1]);
    if (start <= today && start > best) {
      best = start;
      hit = row;
    }
  }
  return { name: hit[2], reading: hit[3], term: hit[4] };
}
