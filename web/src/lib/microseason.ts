///
/// 二十四節気をさらに三つに分けた、およそ 5 日ごとの季節の名前。候の境目は太陽の視黄経で決まり、
/// 立春（315°）から 5° 進むごとに次の候になる。固定の日付表だと年によって 1 日ずれるので、
/// 黄経を端末で計算して引く（外部 API には頼らない。オンプレでも同じに動く）。
///
/// 暦の慣習どおり「境目の瞬間を含む日（日本時間）」をその候の初日とする。
/// 名前・読み・意味は現行の略本暦（宝暦暦を明治に改めたもの）に従う。

export type MicroSeason = {
  /// 候の名前（例: 地始凍）。
  name: string;
  /// 読み（例: ちはじめてこおる）。
  reading: string;
  /// 一言の意味（例: 大地が凍り始める）。
  meaning: string;
  /// 属する二十四節気（例: 立冬）。
  term: string;
  /// 節気の中の位置（初候・次候・末候）。
  phase: "初候" | "次候" | "末候";
};

